pub fn connect() -> Result<Option<Client>> {
    let mut config = if let Ok(url) = env::var("LETTRINE_DATABASE_URL") {
        url.parse::<Config>().context("URL PostgreSQL invalide")?
    } else if let Ok(host) = env::var("LETTRINE_PG_HOST") {
        let mut config = Config::new();
        config.host(&host).user("lettrine").dbname("lettrine");
        if let Ok(password) = env::var("LETTRINE_PG_PASSWORD") {
            config.password(password);
        }
        config
    } else {
        return Ok(None);
    };
    config
        .connect_timeout(Duration::from_secs(5))
        .application_name("lettrine");
    Ok(Some(config.connect(NoTls)?))
}

pub fn initialize(client: &mut Client) -> Result<()> {
    client.batch_execute(
        "
        CREATE TABLE IF NOT EXISTS lab_imports (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            fingerprint text NOT NULL UNIQUE,
            payload jsonb NOT NULL,
            imported_at timestamptz NOT NULL DEFAULT now()
        );
    ",
    )?;
    client.batch_execute(include_str!("../infra/languages.sql"))?;
    client.batch_execute(include_str!("../infra/participants.sql"))?;
    client.batch_execute(include_str!("../infra/move_analytics.sql"))?;
    client.batch_execute(
        "
        CREATE INDEX IF NOT EXISTS lab_games_high_score ON lab_games ((greatest(score_a,score_b)) DESC,id DESC);
        CREATE INDEX IF NOT EXISTS lab_profile_games_high_score ON lab_profile_games (profile,(greatest(score_a,score_b)) DESC,id DESC);
        CREATE TABLE IF NOT EXISTS lab_studies (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            profile text NOT NULL,
            title text NOT NULL,
            summary text NOT NULL,
            kind text NOT NULL,
            artifact text,
            payload jsonb,
            created_at timestamptz NOT NULL DEFAULT now()
        );
    ",
    )?;
    Ok(())
}

pub const FRENCH: &str = "fr-classic-v1";

pub fn meta(client: &mut Client, key: &str, profile: &str) -> Result<Option<Value>> {
    let result = if profile == FRENCH {
        client.query_opt("SELECT value FROM lab_meta WHERE key=$1", &[&key])?
    } else {
        client.query_opt(
            "SELECT value FROM lab_profile_meta WHERE key=$1 AND profile=$2",
            &[&key, &profile],
        )?
    };
    Ok(result.map(|r| r.get(0)))
}

const FILTER: &str = " WHERE ($1::smallint IS NULL OR a=$1 OR b=$1) AND (NOT $2 OR (a=3 AND b=3)) AND ($3::bigint IS NULL OR id=$3 OR seed=$3)";
fn scope(profile: &str) -> (&'static str, &'static str) {
    if profile == FRENCH {
        ("lab_games", " AND $4::text IS NOT NULL")
    } else {
        ("lab_profile_games", " AND profile=$4")
    }
}

pub fn list(client: &mut Client, f: &Filter, profile: &str) -> Result<Value> {
    let (level, elite, q) = f.bindings();
    let level = level.map(i16::from);
    let (table, scope) = scope(profile);
    let total: i64 = client
        .query_one(
            &format!("SELECT count(*) FROM {table}{FILTER}{scope}"),
            &[&level, &elite, &q, &profile],
        )?
        .get(0);
    let stats = if f.sort.as_deref() == Some("elo") {
        meta(client, "public", profile)?.unwrap_or_default()
    } else {
        Value::Null
    };
    let ordering = f.ordering(crate::store::elo_anchors(&stats));
    let rows = client.query(
        &format!("SELECT id,seed,a,b,score_a,score_b,turns,winner FROM {table}{FILTER}{scope} ORDER BY {ordering} LIMIT $5 OFFSET $6"),
        &[&level,&elite,&q,&profile,&i64::from(f.limit.unwrap_or(20).clamp(1,100)),&i64::from(f.offset.unwrap_or(0))]
    )?;
    let items: Vec<_> = rows.iter().map(summary).collect();
    Ok(json!({"items":items,"total":total}))
}

fn summary(r: &Row) -> Value {
    json!({
        "id": r.get::<_,i64>(0), "seed": r.get::<_,i64>(1),
        "levels": [r.get::<_,i16>(2),r.get::<_,i16>(3)], "scores": [r.get::<_,i32>(4),r.get::<_,i32>(5)],
        "turns":r.get::<_,i32>(6), "winner":r.get::<_,Option<i16>>(7)
    })
}

pub fn detail(client: &mut Client, id: u32, profile: &str) -> Result<Option<Vec<u8>>> {
    let id = i64::from(id);
    let result = if profile == FRENCH {
        client.query_opt("SELECT payload::text FROM lab_games WHERE id=$1", &[&id])?
    } else {
        client.query_opt(
            "SELECT payload::text FROM lab_profile_games WHERE id=$1 AND profile=$2",
            &[&id, &profile],
        )?
    };
    Ok(result.map(|r| r.get::<_, String>(0).into_bytes()))
}

pub fn list_imports(client: &mut Client, f: &Filter) -> Result<Value> {
    let total: i64 = client
        .query_one("SELECT count(*) FROM lab_imports", &[])?
        .get(0);
    let items: Vec<Value> = client.query(
        "SELECT id, payload - 'moves' - 'board' FROM lab_imports ORDER BY id DESC LIMIT $1 OFFSET $2",
        &[&i64::from(f.limit.unwrap_or(20).clamp(1,100)),&i64::from(f.offset.unwrap_or(0))]
    )?.into_iter().map(import_payload).collect();
    Ok(json!({"items":items,"total":total}))
}

fn import_payload(row: Row) -> Value {
    let mut payload: Value = row.get(1);
    payload["id"] = json!(row.get::<_, i64>(0));
    payload
}

pub fn imported_game(client: &mut Client, id: u32) -> Result<Option<Value>> {
    Ok(client
        .query_opt(
            "SELECT id,payload FROM lab_imports WHERE id=$1",
            &[&i64::from(id)],
        )?
        .map(import_payload))
}

pub fn export(
    client: &mut Client,
    f: &Filter,
    imports: bool,
    profile: &str,
    mut send: impl FnMut(Vec<u8>) -> Result<()>,
) -> Result<()> {
    let (level, elite, q) = f.bindings();
    let level = level.map(i16::from);
    let params: [&(dyn ToSql + Sync); 4] = [&level, &elite, &q, &profile];
    let (table, scope) = scope(profile);
    let csv = f.format.as_deref() == Some("csv");
    let array = f.format.as_deref() == Some("json");
    let columns = if csv {
        "id,seed,a,b,score_a,score_b,turns,winner"
    } else {
        "payload::text"
    };
    let (sql, bind) = if imports {
        (
            "SELECT payload::text FROM lab_imports ORDER BY id".to_string(),
            &params[..0],
        )
    } else {
        (
            format!("SELECT {columns} FROM {table}{FILTER}{scope} ORDER BY id"),
            &params[..],
        )
    };
    let mut rows = client.query_raw(&sql, bind.iter().copied())?;
    let mut first = true;
    let mut buffer = Vec::with_capacity(64 * 1024);
    if csv {
        buffer.extend(b"id,seed,level_a,level_b,score_a,score_b,turns,winner\n");
    }
    if array {
        buffer.push(b'[');
    }
    while let Some(row) = rows.next()? {
        if csv {
            use std::io::Write;
            let winner = row
                .get::<_, Option<i16>>(7)
                .map(|n| n.to_string())
                .unwrap_or_default();
            writeln!(
                buffer,
                "{},{},{},{},{},{},{},{}",
                row.get::<_, i64>(0),
                row.get::<_, i64>(1),
                row.get::<_, i16>(2),
                row.get::<_, i16>(3),
                row.get::<_, i32>(4),
                row.get::<_, i32>(5),
                row.get::<_, i32>(6),
                winner
            )?;
        } else {
            if array && !first {
                buffer.push(b',');
            }
            buffer.extend(row.get::<_, &str>(0).as_bytes());
            if !array {
                buffer.push(b'\n');
            }
        }
        first = false;
        if buffer.len() >= 64 * 1024 {
            send(std::mem::replace(
                &mut buffer,
                Vec::with_capacity(64 * 1024),
            ))?;
        }
    }
    if array {
        buffer.push(b']');
    }
    if !buffer.is_empty() {
        send(buffer)?;
    }
    Ok(())
}

pub fn search(client: &mut Client, vector: &str) -> Result<Value> {
    let rows = client.query(
        "SELECT title,body,source,1-(embedding <=> ($1::text)::vector) AS similarity
         FROM lab_vectors ORDER BY embedding <=> ($1::text)::vector LIMIT 8",
        &[&vector],
    )?;
    let items: Vec<_> = rows
        .into_iter()
        .map(|r| {
            json!({
                "title":r.get::<_,String>(0), "body":r.get::<_,String>(1),
                "source":r.get::<_,String>(2), "similarity":r.get::<_,f64>(3)
            })
        })
        .collect();
    Ok(json!({"items":items}))
}

pub fn studies(client: &mut Client, profile: &str) -> Result<Vec<Value>> {
    Ok(client.query("SELECT id,to_char(created_at AT TIME ZONE 'UTC','YYYY-MM-DD'),kind,title,summary,artifact FROM lab_studies WHERE profile=$1 ORDER BY id DESC LIMIT 100",&[&profile])?
        .into_iter().map(|r|json!({"id":r.get::<_,i64>(0),"date":r.get::<_,String>(1),"kind":r.get::<_,String>(2),
            "title":r.get::<_,String>(3),"summary":r.get::<_,String>(4),"artifact":r.get::<_,Option<String>>(5)})).collect())
}
pub fn participants(client: &mut Client, profile: &str) -> Result<Value> {
    let rows=client.query("SELECT id,name,kind,elo,source,external_id FROM lab_participants WHERE profile=$1 ORDER BY kind,name,id",&[&profile])?;
    Ok(
        json!({"profile":profile,"items":rows.into_iter().map(|r|json!({"id":r.get::<_,i64>(0),"name":r.get::<_,String>(1),
        "kind":r.get::<_,String>(2),"elo":r.get::<_,Option<i32>>(3),"source":r.get::<_,String>(4),"external_id":r.get::<_,String>(5)})).collect::<Vec<_>>()}),
    )
}
pub fn word_stats(client: &mut Client, profile: &str, f: &Filter) -> Result<Value> {
    let q =
        f.q.as_ref()
            .map(|s| s.trim().to_uppercase())
            .unwrap_or_default();
    let words=client.query("SELECT word,count,mean_score,bingos,openers,premium_turns FROM lab_word_stats
        WHERE profile=$1 AND ($2='' OR left(word,char_length($2))=$2) ORDER BY count DESC,word LIMIT $3 OFFSET $4",
        &[&profile,&q,&i64::from(f.limit.unwrap_or(40).clamp(1,100)),&i64::from(f.offset.unwrap_or(0))])?;
    let items:Vec<_>=words.into_iter().map(|r|json!({"word":r.get::<_,String>(0),"count":r.get::<_,i64>(1),
        "mean_score":r.get::<_,f64>(2),"bingos":r.get::<_,i64>(3),"openers":r.get::<_,i64>(4),"premium_turns":r.get::<_,i64>(5)})).collect();
    let metrics: serde_json::Map<String, Value> = client
        .query(
            "SELECT key,value FROM lab_move_metrics WHERE profile=$1",
            &[&profile],
        )?
        .into_iter()
        .map(|r| (r.get::<_, String>(0), r.get::<_, Value>(1)))
        .collect();
    Ok(json!({"profile":profile,"items":items,"metrics":metrics}))
}

pub fn best_game(client: &mut Client, profile: &str) -> Result<Option<Value>> {
    let sql = if profile == FRENCH {
        "SELECT id,score_a,score_b FROM lab_games ORDER BY greatest(score_a,score_b) DESC,id DESC LIMIT 1"
    } else {
        "SELECT id,score_a,score_b FROM lab_profile_games WHERE profile=$1 ORDER BY greatest(score_a,score_b) DESC,id DESC LIMIT 1"
    };
    let row = if profile == FRENCH {
        client.query_opt(sql, &[])?
    } else {
        client.query_opt(sql, &[&profile])?
    };
    Ok(row.map(|r|json!({"id":r.get::<_,i64>(0),"scores":[r.get::<_,i32>(1),r.get::<_,i32>(2)],"profile":profile})))
}
